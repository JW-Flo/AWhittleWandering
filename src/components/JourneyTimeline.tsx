import React from 'react';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import { MapPin, Calendar, Camera, Star, Mountain, Sunset, Cloud, Zap, Navigation } from 'lucide-react';

interface TimelineEvent {
  id: string;
  state: string;
  date: string;
  type: 'milestone' | 'scenic' | 'adventure' | 'cultural';
  highlights: string[];
  location?: { lat: number; lng: number };
  weather?: { temperature: number; condition: string };
  current?: boolean;
  autoGenerated?: boolean;
}

interface JourneyTimelineProps {
  events?: TimelineEvent[];
  isLoading?: boolean;
  currentLocation?: { lat: number; lng: number } | null;
  batteryLevel?: number;
  isCharging?: boolean;
}

const getTypeIcon = (type: string) => {
  switch (type) {
    case 'milestone': return Star;
    case 'scenic': return Mountain;
    case 'adventure': return Camera;
    case 'cultural': return Sunset;
    default: return MapPin;
  }
};

const getTypeColor = (type: string) => {
  switch (type) {
    case 'milestone': return 'text-adventure-gold';
    case 'scenic': return 'text-adventure-green';
    case 'adventure': return 'text-adventure-orange';
    case 'cultural': return 'text-adventure-purple';
    default: return 'text-primary';
  }
};

